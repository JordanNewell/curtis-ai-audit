/**
 * install.mjs — put the receipt writer on your PATH (INTEGRATION.md Path C).
 *
 *   node install.mjs [bin-dir]        (or: npm run install-writer)
 *
 * Copies bin/curtis-audit-file.mjs plus a `curtis-audit` shim into the target
 * directory — default ~/.local/bin on POSIX, %USERPROFILE%\bin on Windows —
 * and prints a PATH note when needed. Dependency-free: the shim only needs
 * `node` on PATH. Re-running overwrites exactly what it installs, nothing else.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WRITER = "curtis-audit-file.mjs";
const SHIM = "curtis-audit";

const source = path.join(path.dirname(fileURLToPath(import.meta.url)), "bin", WRITER);
const targetDir = path.resolve(
  process.argv[2] ||
    (process.platform === "win32"
      ? path.join(os.homedir(), "bin")
      : path.join(os.homedir(), ".local", "bin"))
);

const SH_SHIM = `#!/usr/bin/env sh
# ${SHIM} — generated by curtis-ai-audit install.mjs
exec node "$(dirname "$0")/${WRITER}" "$@"
`;
const CMD_SHIM = `@echo off
rem ${SHIM} — generated by curtis-ai-audit install.mjs
node "%~dp0${WRITER}" %*
`;

function main() {
  let writerStat;
  try {
    writerStat = fs.statSync(source);
  } catch {
    console.error(`[curtis-audit] ${WRITER} not found at ${source}`);
    console.error("Run this from a curtis-ai-audit checkout (node install.mjs).");
    process.exitCode = 1;
    return;
  }
  if (!writerStat.isFile()) {
    console.error(`[curtis-audit] ${source} is not a file`);
    process.exitCode = 1;
    return;
  }

  fs.mkdirSync(targetDir, { recursive: true });
  const installed = [];
  const copy = (from, to) => {
    fs.copyFileSync(from, to);
    installed.push(to);
  };
  copy(source, path.join(targetDir, WRITER));
  const shShimPath = path.join(targetDir, SHIM);
  fs.writeFileSync(shShimPath, SH_SHIM, { mode: 0o755 });
  installed.push(shShimPath);
  if (process.platform === "win32") {
    const cmdShimPath = path.join(targetDir, `${SHIM}.cmd`);
    fs.writeFileSync(cmdShimPath, CMD_SHIM);
    installed.push(cmdShimPath);
  }

  const ci = (p) => (process.platform === "win32" ? p.toLowerCase() : p);
  const onPath = (process.env.PATH || "")
    .split(path.delimiter)
    .filter(Boolean)
    .some((entry) => ci(path.resolve(entry)) === ci(targetDir));

  console.log("Installed:");
  for (const file of installed) console.log(`  ${file}`);
  if (onPath) {
    console.log(`\nDone — \`${SHIM}\` is on your PATH. Try it:`);
    console.log(`  echo '{"action":"inference","summary":"hello"}' | ${SHIM} --agent test --inbox ./inbox.md`);
  } else {
    console.log(`\nNOTE: ${targetDir} is not on your PATH. Add it:`);
    if (process.platform === "win32") {
      console.log(`  setx Path "%Path%;${targetDir}"    (affects new shells)`);
    } else {
      console.log(`  export PATH="${targetDir}:$PATH"    (add to your shell rc)`);
    }
  }
}

try {
  main();
} catch (err) {
  console.error(`[curtis-audit] install failed: ${err instanceof Error ? err.message : String(err)}`);
  process.exitCode = 1;
}
